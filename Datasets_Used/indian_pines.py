import torch
from torch.utils.data import Dataset

class HSIDataset(Dataset):
    def __init__(self, patches, labels):
        self.patches = patches
        self.labels = labels

    def __len__(self):
        return len(self.labels)

    def __getitem__(self, idx):
        multi = self.patches[idx]

        # stack scales → (scales, H, W, C)
        multi = [torch.tensor(p).permute(2,0,1).float() for p in multi]

        return multi, torch.tensor(self.labels[idx])

import torch.nn as nn

class PatchEncoder(nn.Module):
    def __init__(self, in_ch=30, dim=128):
        super().__init__()
        self.conv = nn.Conv2d(in_ch, dim, 3, padding=1)
        self.pool = nn.AdaptiveAvgPool2d(1)

    def forward(self, x):
        x = self.conv(x)
        x = self.pool(x).squeeze(-1).squeeze(-1)
        return x

class MAE(nn.Module):
    def __init__(self, dim=128):
        super().__init__()
        self.encoder = nn.Linear(dim, dim)
        self.decoder = nn.Linear(dim, dim)

    def forward(self, x):
        z = self.encoder(x)
        return self.decoder(z)

import torch.nn.functional as F

def contrastive_loss(z1, z2, T=0.5):
    z1 = F.normalize(z1, dim=1)
    z2 = F.normalize(z2, dim=1)

    logits = z1 @ z2.T / T
    labels = torch.arange(z1.size(0)).to(z1.device)

    return F.cross_entropy(logits, labels)

class ViT(nn.Module):
    def __init__(self, dim=128, heads=4):
        super().__init__()
        self.attn = nn.MultiheadAttention(dim, heads, batch_first=True)
        self.norm = nn.LayerNorm(dim)

    def forward(self, x):
        # x: (B, D) → make sequence length = 1
        x = x.unsqueeze(1)  # (B, 1, D)

        out,_ = self.attn(x, x, x)
        return self.norm(out + x).squeeze(1)  # (B, D)

