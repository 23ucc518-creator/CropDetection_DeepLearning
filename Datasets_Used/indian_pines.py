def build_node_features(features, segments):
    import numpy as np
    nodes = np.unique(segments)
    node_feats = []

    for n in nodes:
        mask = segments == n
        node_feats.append(features[mask].mean(axis=0))

    return np.array(node_feats)

class GraphTransformer(nn.Module):
    def __init__(self, dim=128):
        super().__init__()
        self.attn = nn.MultiheadAttention(dim, 4, batch_first=True)
        self.norm = nn.LayerNorm(dim)

    def forward(self, x):
        x = x.unsqueeze(1)  # (B, 1, D)

        out,_ = self.attn(x, x, x)
        return self.norm(out + x).squeeze(1)

class Fusion(nn.Module):
    def __init__(self, dim=128):
        super().__init__()
        self.fc = nn.Linear(dim*2, dim)

    def forward(self, spectral, spatial):
        return self.fc(torch.cat([spectral, spatial], dim=-1))

class FullModel(nn.Module):
    def __init__(self, num_classes):
        super().__init__()

        self.encoder = PatchEncoder()
        self.vit = ViT()
        self.graph = GraphTransformer()
        self.fusion = Fusion()
        self.classifier = nn.Linear(128, num_classes)

    def forward(self, x):
      # x shape: (B, C, H, W)

      feat = self.encoder(x)         # (B, 128)
      vit_feat = self.vit(feat)      # (B, 128)
      graph_feat = self.graph(vit_feat)  # (B, 128)

      fused = self.fusion(vit_feat, graph_feat)

      return self.classifier(fused)  # (B, num_classes)

