def extract_patches(data, labels, patch_size=9):
    margin = patch_size // 2
    padded = np.pad(data, ((margin, margin), (margin, margin), (0, 0)), mode='reflect')

    patches = []
    patch_labels = []

    for i in range(margin, data.shape[0] + margin):
        for j in range(margin, data.shape[1] + margin):

            label = labels[i - margin, j - margin]
            if label == 0:
                continue  # ignore unlabeled

            patch = padded[i - margin:i + margin + 1, j - margin:j + margin + 1]
            patches.append(patch)
            patch_labels.append(label - 1)

    return np.array(patches), np.array(patch_labels)

